/* ==========================================================================
   旧「工作日历维护」页（/attendance/calendar）已被独立页面替代 —— 重定向存根
   --------------------------------------------------------------------------
   为什么整页替换而不是继续打补丁：
     旧页有三处写死的交互缺陷，补丁改不动：
       1) 切到没有记录的月份时，代码把规则静默重置回 5day
          （x() 里的 `e ? ... : (r.value="5day", u.value={})`），
          用户看到的现象就是「明明选了六天工作制，一下就跳回五天」。
       2) 日历网格从 1 号起顺序平铺 7 列，不按星期对齐，也没有星期表头。
       3) 日期面板里翻月只是切面板，不改 modelValue，必须点中具体月份才生效，
          用户点箭头会以为「切月份没反应」。

   替代页面：/work-calendar.html（OAShell 范式，逻辑全在页面内，可维护）
   回滚：把 WorkCalendar-BRgZTk57.js.bak-wcweek-20261027.v1 复制回本文件名。
   ========================================================================== */
export default {
  name: 'WorkCalendarLegacyRedirect',
  setup() {
    try {
      location.replace('/work-calendar.html' + (location.search || ''));
    } catch (e) { /* noop */ }
  },
  render() { return null; }
};
