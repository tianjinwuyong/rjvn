from pathlib import Path

SPEC_DIR = Path(__file__).resolve().parent
FORMAL = SPEC_DIR.parent
ASSEMBLY = SPEC_DIR / "(07)组装ATE"
AUTO = next(p for p in FORMAL.iterdir() if p.is_dir() and p.name.startswith("002-"))
RESERVOIR = FORMAL / "station-component-reservoir" / "python"
MANUAL_REPAIR = SPEC_DIR / "manual_repair"
STORE = SPEC_DIR / "repair_work_order_store.py"
COMMON = SPEC_DIR / "atecommonagent.py"

COMMON_HIDDEN = [
    "atecommonagent", "station_arrival_core", "station_excel_events",
    "station_excel_safe", "station_common_agent", "station_common_bootstrap",
    "station_runtime_safety", "station_i18n", "station_retest", "station_history_core",
    "station_language", "station_heartbeat", "station_ui_primitives",
    "station_scan_alarm", "station_arrival_ui",
    "station_repair_workflow", "repair_work_order_store", "station_resource_viewer",
    "station_components.ng_closed_loop", "station_components.repair_cycle_graph",
    "pynput.keyboard", "tkinter.filedialog", "tkinter.messagebox",
    "tkinter.ttk", "tkinter.simpledialog", "tkinter.scrolledtext",
]

def make_spec(entry_dir, entry_name, exe_name, station_code, next_station, display_name, db_name, scanner_port):
    repair = ASSEMBLY / "dist" / "assembly_ate_agent" / "_internal" / "manual_repair" / "station_repair_workflow.py"
    datas = [(str(p), ASSEMBLY.name) for p in ASSEMBLY.glob("*.py")]
    if repair.exists():
        datas.append((str(repair), "manual_repair"))
    if STORE.exists():
        datas.append((str(STORE), "manual_repair"))
    datas.append((str(COMMON), "."))
    launcher = entry_dir / entry_name
    return f'''# generated by build_ate_common_specs.py
from PyInstaller.building.build_main import Analysis, PYZ, EXE, COLLECT

a = Analysis(
    [{str(launcher)!r}],
    pathex=[{str(entry_dir)!r}, {str(SPEC_DIR)!r}, {str(ASSEMBLY)!r}, {str(AUTO)!r}, {str(RESERVOIR)!r}],
    binaries=[],
    datas={datas!r},
    hiddenimports={COMMON_HIDDEN!r},
    hookspath=[], hooksconfig={{}}, runtime_hooks=[],
    excludes=["PySide6", "shiboken6", "numpy", "pandas", "lxml", "matplotlib", "scipy"],
    noarchive=False, optimize=0,
)
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name={exe_name!r},
          debug=False, bootloader_ignore_signals=False, strip=False, upx=False,
          console=True, disable_windowed_traceback=False, argv_emulation=False,
          target_arch=None, codesign_identity=None, entitlements_file=None)
coll = COLLECT(exe, a.binaries, a.datas, strip=False, upx=False, upx_exclude=[], name={exe_name!r})
'''

configs = [
    ("(07)组装ATE", "assembly_ate_agent.py", "assembly_ate_agent", "manu_assem_ate", "manu_hivolt_ate", "Assembly ATE / 2D", "assembly_ate_agent.db", "1009"),
    ("(10)高压ATE", "hivolt_ate_agent.py", "hivolt_ate_agent", "manu_hivolt_ate", "manu_package_ate", "High-Voltage ATE / 2D", "hivolt_ate_agent.db", "1010"),
    ("(11)包装ATE", "packing_ate_agent.py", "packing_ate_agent", "manu_package_ate", "manu_outer_box_binding", "Packaging ATE / 2D", "packing_ate_agent.db", "1011"),
]

for dirname, entry, exe, code, nxt, title, db, port in configs:
    folder = SPEC_DIR / dirname
    (folder / f"{exe}_common.spec").write_text(
        make_spec(folder, entry, exe, code, nxt, title, db, port), encoding="utf-8"
    )
